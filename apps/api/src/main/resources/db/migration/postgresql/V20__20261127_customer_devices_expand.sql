-- V20 - customer_devices (aparelho fisico) separado de devices (OS)

-- 1. Aparelho fisico ----------------------------------------------------------
CREATE TABLE customer_devices (
    id                  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_customer         integer      NOT NULL,
    id_brand_model_type integer      NOT NULL,
    color_ids           integer[]    NOT NULL,
    serial_number       varchar(120),
    label               varchar(120),
    physical_notes      text,
    created_at          timestamp    NOT NULL DEFAULT now(),
    updated_at          timestamp    NOT NULL DEFAULT now(),
    version             bigint       NOT NULL DEFAULT 0,
    CONSTRAINT fk_customer_devices_customers
        FOREIGN KEY (id_customer) REFERENCES customers (id),
    CONSTRAINT fk_customer_devices_brand_model_type
        FOREIGN KEY (id_brand_model_type) REFERENCES brands_models_types (id)
);

INSERT INTO customer_devices (id, id_customer, id_brand_model_type, color_ids, created_at, updated_at)
SELECT d.id, d.id_customer, d.id_brand_model_type, d.color_ids, d.entry_date,
       COALESCE(d.last_update, d.entry_date)
FROM devices d;

SELECT setval(pg_get_serial_sequence('customer_devices', 'id'),
              COALESCE((SELECT MAX(id) FROM customer_devices), 1),
              (SELECT COUNT(*) > 0 FROM customer_devices));

-- 2. Colunas novas da OS ---------------------------------------------------------
ALTER TABLE devices
    ADD COLUMN id_customer_device integer,
    ADD COLUMN id_origin_order    integer,
    ADD COLUMN warranty_days      integer DEFAULT 90,
    ADD COLUMN public_token       uuid NOT NULL DEFAULT gen_random_uuid(),
    ADD COLUMN closed_at          timestamp;

UPDATE devices SET id_customer_device = id;

ALTER TABLE devices
    ALTER COLUMN id_customer_device SET NOT NULL,
    ADD CONSTRAINT fk_devices_customer_devices
        FOREIGN KEY (id_customer_device) REFERENCES customer_devices (id),
    ADD CONSTRAINT fk_devices_origin_order
        FOREIGN KEY (id_origin_order) REFERENCES devices (id),
    ADD CONSTRAINT uq_devices_public_token UNIQUE (public_token),
    ADD CONSTRAINT chk_devices_warranty_days_non_negative
        CHECK (warranty_days IS NULL OR warranty_days >= 0);

UPDATE devices SET warranty_days = NULL WHERE device_status IN ('NAO_APROVADO', 'DESCARTADO');

UPDATE devices
SET closed_at = departure_date
WHERE device_status IN ('ENTREGUE', 'DESCARTADO')
  AND departure_date IS NOT NULL;

UPDATE devices d
SET closed_at = h.last_close
FROM (
    SELECT id_device, MAX(history_date) AS last_close
    FROM device_history
    WHERE field_name = 'device_status'
      AND new_value IN ('ENTREGUE', 'DESCARTADO')
    GROUP BY id_device
) h
WHERE h.id_device = d.id
  AND d.device_status IN ('ENTREGUE', 'DESCARTADO')
  AND d.departure_date IS NULL;

UPDATE devices
SET closed_at = last_update
WHERE device_status IN ('ENTREGUE', 'DESCARTADO')
  AND departure_date IS NULL
  AND closed_at IS NULL
  AND last_update >= TIMESTAMP '2026-06-16 00:00:00';

UPDATE devices d
SET is_revision = true
WHERE d.is_revision = false
  AND EXISTS (
      SELECT 1 FROM device_history h
      WHERE h.id_device = d.id
        AND h.field_name = 'revision'
        AND h.new_value = 'true'
  );

-- 3. Catalogo de acessorios ----------------------------------------
CREATE TABLE accessories (
    id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       varchar(120) NOT NULL,
    name_key   text GENERATED ALWAYS AS
                   (regexp_replace(lower(public.immutable_unaccent(name)), '[^a-z0-9]', '', 'g')) STORED,
    created_at timestamp    NOT NULL DEFAULT now(),
    updated_at timestamp    NOT NULL DEFAULT now(),
    CONSTRAINT chk_accessories_name_key_not_empty CHECK (name_key <> '')
);

CREATE UNIQUE INDEX idx_accessories_name_key_unique ON accessories (name_key);

CREATE TABLE service_order_accessories (
    id_service_order integer NOT NULL,
    id_accessory     integer NOT NULL,
    CONSTRAINT pk_service_order_accessories PRIMARY KEY (id_service_order, id_accessory),
    CONSTRAINT fk_service_order_accessories_devices
        FOREIGN KEY (id_service_order) REFERENCES devices (id),
    CONSTRAINT fk_service_order_accessories_accessories
        FOREIGN KEY (id_accessory) REFERENCES accessories (id)
);

-- 4. Indices ---------------------------------------------------------------------
CREATE INDEX ix_devices_id_customer_device ON devices (id_customer_device);
CREATE INDEX ix_devices_id_origin_order ON devices (id_origin_order) WHERE id_origin_order IS NOT NULL;
CREATE INDEX ix_customer_devices_id_customer ON customer_devices (id_customer);
CREATE INDEX ix_customer_devices_id_brand_model_type ON customer_devices (id_brand_model_type);
CREATE INDEX ix_customer_devices_label_trgm
    ON customer_devices USING gin (LOWER(public.immutable_unaccent(label)) gin_trgm_ops)
    WHERE label IS NOT NULL;
CREATE INDEX ix_customer_devices_serial_number_trgm
    ON customer_devices USING gin (LOWER(serial_number) gin_trgm_ops)
    WHERE serial_number IS NOT NULL;
CREATE INDEX ix_service_order_accessories_id_accessory ON service_order_accessories (id_accessory);

-- 5. Compatibilidade com quem ainda nao conhece customer_devices -----------------
CREATE FUNCTION devices_fill_customer_device() RETURNS trigger
    LANGUAGE plpgsql AS
$$
BEGIN
    IF NEW.id_customer_device IS NULL THEN
        INSERT INTO customer_devices (id_customer, id_brand_model_type, color_ids, created_at, updated_at)
        VALUES (NEW.id_customer, NEW.id_brand_model_type, NEW.color_ids,
                COALESCE(NEW.entry_date, now()), COALESCE(NEW.entry_date, now()))
        RETURNING id INTO NEW.id_customer_device;
    END IF;
    RETURN NEW;
END
$$;

CREATE TRIGGER trg_devices_fill_customer_device
    BEFORE INSERT ON devices
    FOR EACH ROW
EXECUTE FUNCTION devices_fill_customer_device();
